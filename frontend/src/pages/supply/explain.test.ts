import { describe, expect, it } from "vitest";
import { explainSupply } from "./explain";

import { NBSP as N } from "../../lib/format";

describe("объяснение поставки с единицами", () => {
  it("расход, запас и заказ — с единицами и десятичной запятой", () => {
    const raw =
      "Расход ~1692 в день, пригодный запас 600 хватит на 0.4 сут.; нужно на 5 сут. (доставка 2 + покрытие 3). К заказу 7000 (упаковка 1000). Блокирует блюд из стоп-листа: 2.";
    expect(explainSupply(raw, "ml")).toBe(
      `≈${N}1,7${N}л в день, запас 600${N}мл хватит на 0,4${N}сут.; нужно на 5${N}сут. (доставка 2 + покрытие 3). К заказу 7${N}л (7${N}уп. по 1${N}л). Блокирует блюд из стоп-листа: 2.`,
    );
  });
  it("граммы и штуки", () => {
    const raw = "Расход ~800 в день, пригодный запас 100 хватит на 0.1 сут.; нужно на 2 сут. (доставка 1 + покрытие 1). К заказу 1500 (упаковка 500).";
    expect(explainSupply(raw, "g")).toContain(`≈${N}800${N}г в день, запас 100${N}г`);
    expect(explainSupply(raw, "g")).toContain(`К заказу 1,5${N}кг (3${N}уп. по 500${N}г).`);
    expect(explainSupply("Расход ~3 в день, пригодный запас 1 хватит на 0.3 сут.; нужно на 1 сут. (доставка 1 + покрытие 0). К заказу 10 (упаковка 10).", "pcs")).toContain(`10${N}шт (1${N}уп. по 10${N}шт)`);
  });
  it("нулевой расход", () => {
    const raw = "Расхода нет; минимальный запас — 5 порций × норма 200 = 1000, пригодный запас 0. К заказу 1000 (упаковка 1000).";
    expect(explainSupply(raw, "g")).toBe(
      `Расхода нет; минимальный запас — 5 порций × норма 200${N}г = 1${N}кг, пригодный запас 0${N}г. К заказу 1${N}кг (1${N}уп. по 1${N}кг).`,
    );
  });
  it("неизвестный шаблон — текст как есть", () => {
    expect(explainSupply("что-то другое", "g")).toBe("что-то другое");
  });
});
